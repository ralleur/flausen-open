#!/usr/bin/env python3
"""Generate brand bindings from the unmodified supplied token source."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent

def generate():
    tokens = json.loads((ROOT/'handoff/DESIGN_TOKENS.json').read_text())
    output = ROOT/'generated'
    output.mkdir(exist_ok=True)
    (output/'Brand.js').write_text('// Generated by branding/flausen/generate.py; edit DESIGN_TOKENS.json.\n.pragma library\nvar tokens = '+json.dumps(tokens, ensure_ascii=False, indent=2)+';\n')
    identity = dict(tokens['brand'], id='flausen-os', descriptor='Everyday OS', status='development')
    (output/'identity.json').write_text(json.dumps(identity,ensure_ascii=False,indent=2)+'\n')
    # Use the installed schema's complete role set, retained in this repository.
    template = (ROOT.parents[1]/'kde-customizations/themes/graphite-blue/default/dark.txt').read_text()
    baseline = dict(line.split() for line in template.splitlines() if line and not line.startswith('#'))
    for mode in ('dark','light'):
        c = tokens['color'][mode]; b = tokens['color']['brand']; sem = tokens['color']['semantic']
        roles = dict(baseline)
        for role in roles:
            roles[role] = c['textMuted'].lstrip('#')
        assignments = {
            'background crust': c['background'],
            'surface base surfaceDim surfaceContainerLow mantle': c['surface'],
            'surfaceBright surfaceContainer surfaceContainerHigh surfaceContainerHighest surface0 surface1 surface2': c['surfaceRaised'],
            'onBackground onSurface text term7 term15': c['text'],
            'onSurfaceVariant subtext0 subtext1 outline overlay0 overlay1 overlay2': c['textMuted'],
            'surfaceVariant outlineVariant neutral_variant_paletteKeyColor': c['border'],
            'primary primary_paletteKeyColor surfaceTint inversePrimary klink klinkSelection term4 term12 blue sapphire': c['focus'],
            'onPrimary onSecondary onTertiary onError onSuccess inverseOnSurface': c['background'],
            'primaryContainer secondaryContainer tertiaryContainer errorContainer successContainer': c['selected'],
            'onPrimaryContainer onSecondaryContainer onTertiaryContainer onErrorContainer onSuccessContainer': c['text'],
            'secondary secondary_paletteKeyColor yellow term3 term11 kneutral kneutralSelection': b['yellow'],
            'tertiary tertiary_paletteKeyColor peach rosewater flamingo pink': b['coral'],
            'error red maroon term1 term9 knegative knegativeSelection': sem['error'],
            'success green term2 term10 kpositive kpositiveSelection': sem['success'],
            'term0 term8': c['background'],
            'inverseSurface': c['text'], 'shadow scrim': '#000000',
        }
        for keys,value in assignments.items():
            for key in keys.split(): roles[key]=value.lstrip('#')
        # Readable labels on accent backgrounds; blue dark-mode focus requires dark ink.
        roles['onPrimary'] = (tokens['color']['light']['text'] if mode=='dark' else tokens['color']['light']['surface']).lstrip('#')
        for family in ('primary','secondary','tertiary'):
            roles[family+'Fixed'] = roles[family]
            roles[family+'FixedDim'] = roles[family]
            roles['on'+family.title()+'Fixed'] = c['background'].lstrip('#')
            roles['on'+family.title()+'FixedVariant'] = c['text'].lstrip('#')
        dest=output/'schemes/flausen/default';dest.mkdir(parents=True,exist_ok=True)
        (dest/(mode+'.txt')).write_text('# Generated from flausen DESIGN_TOKENS.json\n'+''.join(k+' '+v+'\n' for k,v in roles.items()))
    session = ROOT.parents[1]/"kde-customizations/session-style/shared"
    if session.is_dir():
        (session/"FlausenBrand.js").write_bytes((output/"Brand.js").read_bytes())
    return output
if __name__=='__main__': print(generate())
